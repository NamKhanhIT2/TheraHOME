const fs = require('fs');
const path = require('path');
const { withDangerousMod, withGradleProperties } = require('expo/config-plugins');

/**
 * Turns R8 on for Android release builds, and tells it what not to touch.
 *
 * Play Console reports "DEX optimisation: Low" on every build this app has
 * ever uploaded, because Expo's template ships
 * `android.enableMinifyInReleaseBuilds=false`. Nothing is shrunk, nothing
 * is obfuscated, and the uncompressed DEX is 55 MB.
 *
 * Two halves, and the second is the one that matters:
 *
 *  - the gradle properties: the flag itself, plus a bigger daemon, because
 *    R8 does not fit in the one Expo's template configures,
 *  - the keep rules in plugins/android-keep-rules.pro, which are the whole
 *    risk. R8 deletes and renames anything it cannot see being used, and
 *    it cannot see JNI, a manifest string or a reflective lookup. Those
 *    failures do not appear in a debug build, do not fail the gradle
 *    build, and surface on a customer's phone.
 *
 * Both have to be a config plugin: `android/` is generated by
 * `expo prebuild` and gitignored, so a hand edit to gradle.properties or
 * to app/proguard-rules.pro lasts until the next native config change.
 *
 * The rules live in a .pro file rather than in `extraProguardRules` inside
 * app.json because they need comments. A rule nobody can explain is a rule
 * nobody dares delete.
 */

const MARKER = '# @therahome-r8';

/** R8 runs inside the Gradle daemon, and Expo's template gives that daemon
 * 2 GB of heap and 512 MB of metaspace. On this app that is not enough: the
 * first release build with minification on died in `minifyReleaseWithR8`
 * with "the JVM garbage collector is thrashing and after running out of JVM
 * Metaspace" — a failure that looks like a broken keep rule and is not one.
 * Raised here rather than in a README, because the person who hits it will
 * be whoever next runs a release build on a different machine. */
const JVM_ARGS = '-Xmx6144m -XX:MaxMetaspaceSize=2048m';

const PROPERTIES = {
  'android.enableMinifyInReleaseBuilds': 'true',
  'org.gradle.jvmargs': JVM_ARGS,
};

const withMinify = (config) =>
  withGradleProperties(config, (config) => {
    for (const [key, value] of Object.entries(PROPERTIES)) {
      const existing = config.modResults.find(
        (item) => item.type === 'property' && item.key === key,
      );
      if (existing) existing.value = value;
      else config.modResults.push({ type: 'property', key, value });
    }
    return config;
  });

const withKeepRules = (config) =>
  withDangerousMod(config, ['android', async (config) => {
    const target = path.join(config.modRequest.platformProjectRoot, 'app', 'proguard-rules.pro');
    // Written by the prebuild template before any mod runs. Absent means
    // the template changed, and silently creating one would hide that.
    if (!fs.existsSync(target)) {
      throw new Error('withAndroidR8: ' + target + ' does not exist. The Android template changed.');
    }
    const current = fs.readFileSync(target, 'utf8');
    if (current.includes(MARKER)) return config;
    const rules = fs.readFileSync(path.join(__dirname, 'android-keep-rules.pro'), 'utf8');
    fs.writeFileSync(target, current + '\n' + MARKER + ' — appended by plugins/withAndroidR8.js\n' + rules);
    return config;
  }]);

module.exports = (config) => withKeepRules(withMinify(config));
