-- An order placed in the app was never stored as an order.
--
-- `place-app-order` wrote the order into the customer's support thread as a
-- chat message, raised a staff alert and sent a receipt — three copies of the
-- same paragraph of text, and not one row anybody could filter, search, count
-- or mark as delivered. Managing orders meant scrolling a chat thread
-- (owner, 2026-11-01).
--
-- This is deliberately NOT the existing `orders` table. That one is the
-- Shopify/activation feed: it carries an activation_code, it is what
-- `claim_user_access_contact` checks a purchase against, and a row landing in
-- it queues the buyer's phone into `product_activation_contacts`. An in-app
-- order grants no app access and must not look like it does.

create table if not exists public.app_orders (
  id uuid primary key default gen_random_uuid(),
  -- The 8-char code the customer sees in their receipt and reads out on the
  -- phone. Generated by the Edge Function, unique so CSKH can search by it.
  reference text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  -- Catalogue rows get renamed and repriced; an order has to keep saying what
  -- was actually bought and for how much, so name and prices are snapshots,
  -- not joins.
  store_item_id text references public.store_items(id) on delete set null,
  product_name text not null,
  market text not null,
  quantity integer not null check (quantity between 1 and 10),
  list_price numeric(12, 2) not null,
  unit_price numeric(12, 2) not null,
  discount_percent smallint not null default 0,
  total_amount numeric(12, 2) not null,
  customer_name text not null,
  phone text not null,
  -- Digits only, so a search for 0328552894 also finds "032 855 2894".
  phone_digits text not null,
  address text not null,
  note text,
  status text not null default 'new'
    check (status in ('new', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  staff_note text,
  handled_by uuid references auth.users(id) on delete set null,
  handled_at timestamptz,
  -- Where the conversation about this order lives. Nullable on delete so
  -- clearing a test thread can never take the order row with it.
  thread_id uuid references public.chat_threads(id) on delete set null,
  message_id uuid references public.chat_messages(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists app_orders_created_at_idx on public.app_orders (created_at desc);
create index if not exists app_orders_status_idx on public.app_orders (status);
create index if not exists app_orders_phone_digits_idx on public.app_orders (phone_digits);
create index if not exists app_orders_user_idx on public.app_orders (user_id);

-- Who touched it last, without every caller remembering to set it.
create or replace function public.touch_app_order()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  -- The first move away from 'new' is the moment somebody took the order on.
  if new.status is distinct from old.status and old.handled_at is null and new.status <> 'new' then
    new.handled_at := now();
    new.handled_by := coalesce(new.handled_by, auth.uid());
  end if;
  return new;
end;
$$;

drop trigger if exists touch_app_order on public.app_orders;
create trigger touch_app_order
  before update on public.app_orders
  for each row execute function public.touch_app_order();

alter table public.app_orders enable row level security;

-- Staff read and work the queue. Inserts belong to the Edge Function alone
-- (service_role bypasses RLS), so there is no insert policy for anybody:
-- an order is a record of what the app charged, not something typed in here.
create policy "web staff read app_orders" on public.app_orders
  for select using (
    'admin' = any (current_web_roles()) or 'cskh' = any (current_web_roles())
  );

create policy "web staff update app_orders" on public.app_orders
  for update using (
    'admin' = any (current_web_roles()) or 'cskh' = any (current_web_roles())
  ) with check (
    'admin' = any (current_web_roles()) or 'cskh' = any (current_web_roles())
  );

-- The buyer may read their own, so "đơn của tôi" in the app needs no further
-- migration later.
create policy "customer reads own app_orders" on public.app_orders
  for select using (user_id = auth.uid());

comment on table public.app_orders is
  'Orders placed inside the mobile app store. Written only by the place-app-order Edge Function; worked by Admin/CSKH in the web console. Grants no app access — see the orders table for the Shopify/activation feed.';
